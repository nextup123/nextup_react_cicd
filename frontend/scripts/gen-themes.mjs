// Generates src/styles/themes.css: one accent scale per accent × mode.
// Run: node scripts/gen-themes.mjs   (prints a contrast report)
//
// Every accent is checked in every mode: white text on --primary-600 (filled
// buttons), --primary-700 on --primary-50 (selected nav item, soft buttons)
// and --primary-ink on the page surface (links, icons) must all reach 4.5:1.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { ACCENTS, MODES } from "../src/lib/themeList.js";

const hex2rgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const rgb2hex = (c) => "#" + c.map((v) => Math.round(Math.max(0, Math.min(255, v))).toString(16).padStart(2, "0")).join("");
const mix = (a, b, t) => rgb2hex(hex2rgb(a).map((v, i) => v * (1 - t) + hex2rgb(b)[i] * t)); // t = share of b
const lum = (h) => {
  const [r, g, b] = hex2rgb(h).map((v) => {
    v /= 255;
    return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const contrast = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};
// Move `c` towards `to` in small steps until test(c) holds.
const until = (c, to, test) => {
  for (let t = 0; t <= 1; t += 0.02) {
    const m = mix(c, to, t);
    if (test(m)) return m;
  }
  return to;
};
const alpha = (h, a) => `rgba(${hex2rgb(h).join(", ")}, ${a})`;

function scale(base, mode) {
  const { surface, dark } = MODES[mode];
  if (!dark) {
    const p600 = until(mix(base, "#000000", 0.12), "#000000", (c) => contrast(c, "#ffffff") >= 4.6);
    const p50 = mix(base, surface, 0.9);
    const p700 = until(mix(p600, "#000000", 0.15), "#000000", (c) => contrast(c, p50) >= 6.5);
    return {
      50: p50, 100: mix(base, surface, 0.84), 200: mix(base, surface, 0.66),
      500: base, 600: p600, 700: p700, ink: until(p600, "#000000", (c) => contrast(c, surface) >= 4.6),
      ring: alpha(base, 0.24), soft: alpha(base, 0.1),
    };
  }
  // Dark: the brightest fill that still carries white text, light text on tints.
  let p600 = until(base, "#000000", (c) => contrast(c, "#ffffff") >= 4.5);
  for (let t = 0.3; t >= 0; t -= 0.02) {
    const c = mix(base, "#ffffff", t);
    if (contrast(c, "#ffffff") >= 4.5) { p600 = c; break; }
  }
  const p50 = mix(base, surface, 0.8);
  const p700 = until(mix(base, "#ffffff", 0.45), "#ffffff", (c) => contrast(c, p50) >= 7);
  return {
    50: p50, 100: mix(base, surface, 0.7), 200: mix(base, surface, 0.5),
    500: mix(base, "#ffffff", 0.18), 600: p600, 700: p700,
    ink: until(mix(base, "#ffffff", 0.3), "#ffffff", (c) => contrast(c, surface) >= 5),
    ring: alpha(mix(base, "#ffffff", 0.2), 0.35), soft: alpha(mix(base, "#ffffff", 0.2), 0.14),
  };
}

let css = "/* Generated by scripts/gen-themes.mjs — do not edit by hand. */\n";
const report = [];
for (const mode of Object.keys(MODES)) {
  for (const a of ACCENTS) {
    const s = { ...scale(a.color, mode), ...(a.exact?.[mode] || {}) };
    const sel = mode === "light" ? `:root[data-accent="${a.id}"]` : `:root[data-mode="${mode}"][data-accent="${a.id}"]`;
    const fallback = a.id === ACCENTS[0].id ? (mode === "light" ? ":root, " : `:root[data-mode="${mode}"], `) : "";
    css += `${fallback}${sel} { --primary-50: ${s[50]}; --primary-100: ${s[100]}; --primary-200: ${s[200]}; --primary-500: ${s[500]}; --primary-600: ${s[600]}; --primary-700: ${s[700]}; --primary-ink: ${s.ink}; --primary-soft: ${s.soft}; --ring: 0 0 0 3px ${s.ring}; }\n`;
    const surf = MODES[mode].surface;
    report.push([mode, a.id, contrast(s[600], "#ffffff"), contrast(s[700], s[50]), contrast(s.ink, surf), contrast(s[600], surf)].map((v) => (typeof v === "number" ? v.toFixed(2) : v)).join("\t"));
  }
}

writeFileSync(fileURLToPath(new URL("../src/styles/themes.css", import.meta.url)), css);
console.log("mode\taccent\twhite/600\t700/50\tink/surf\t600/surf");
