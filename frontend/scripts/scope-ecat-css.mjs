// Generates src/pages/ethercat/ecat.css from the EtherCAT Config Tool's client/src/styles.css:
// every rule is scoped under .ecat, the tool's own shell (sidebar, header, toasts, theme switch,
// fonts) is dropped, its dark theme follows NextUp's mode, keyframes get an ecat- prefix and
// endless eased animations become steps(2) (CPU, see README "Round 21").
//
//   node scripts/scope-ecat-css.mjs <path to the tool's client/src/styles.css>
//
// The tool's colour tokens are mapped onto NextUp's at the top of the output, so the drive
// pages take the chosen accent and light / gray / dark mode. Edit ecat-extra.css for
// NextUp-specific changes; re-running this overwrites ecat.css.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = process.argv[2];
if (!src) { console.error("usage: node scripts/scope-ecat-css.mjs <styles.css>"); process.exit(1); }
const out = path.join(here, "..", "src", "pages", "ethercat", "ecat.css");

// The tool's shell: NextUp draws its own.
const DROP = /^(html|body|#root|\.shell|\.sidebar|\.brand|\.nav\b|\.nav-|\.icon-btn\.nav-close|\.icon-btn\.menu-btn|\.sidebar-foot|\.theme-btn|\.version|\.main\b|\.header\b|\.header-|\.scrim|\.toasts?\b|\.toast-|\.content\b|\.content\.flush|::-webkit-scrollbar|::selection|:focus-visible|\.nav-open)/;

const TOKENS = `/* ecat.css -- GENERATED by scripts/scope-ecat-css.mjs from the EtherCAT Config Tool styles:
   every rule is scoped under .ecat. Edit ecat-extra.css instead. */
/* the tool's colour names on NextUp's tokens (accent, light / gray / dark mode) */
.ecat {
  --bg-2: var(--surface-3);
  --text-3: var(--text-muted);
  --accent: var(--primary-600);
  --accent-hover: var(--primary-700);
  --accent-ink: var(--on-primary, #fff);
  --accent-soft: var(--primary-soft);
  --accent-line: var(--primary-200);
  --ring: var(--primary-soft);
  --ok: var(--success-text);
  --ok-soft: var(--success-bg);
  --ok-line: var(--success-border);
  --warn: var(--warning-text);
  --warn-soft: var(--warning-bg);
  --warn-line: var(--warning-border);
  --danger: var(--danger-text);
  --danger-soft: var(--danger-bg);
  --danger-line: var(--danger-border);
  --danger-solid: var(--danger-600, #c81e1e);
  --shadow: var(--shadow-xs);
  --shadow-pop: var(--shadow-lg), 0 0 0 1px var(--border);
  --overlay: var(--backdrop);
  --mark: var(--warning-border);
  --r: var(--radius);
  --r-sm: var(--radius-sm);
  --pad: 16px;
  --ease: cubic-bezier(0.2, 0.8, 0.2, 1);
  font-size: 14px;
  line-height: 1.45;
  color: var(--text);
}
`;

const scope = (sel) => {
  sel = sel.trim();
  if (/^\[data-theme="dark"\]\s*/.test(sel)) return `:root[data-mode="dark"] .ecat ${sel.replace(/^\[data-theme="dark"\]\s*/, "")}`;
  if (/^\[data-theme="light"\]\s*/.test(sel)) return `:root:not([data-mode="dark"]) .ecat ${sel.replace(/^\[data-theme="light"\]\s*/, "")}`;
  return `.ecat ${sel}`;
};

const css = fs.readFileSync(src, "utf8");
const root = postcss.parse(css);
root.walkAtRules((at) => {
  if (at.name === "font-face") at.remove();
  else if (at.name === "keyframes") at.params = `ecat-${at.params}`;
});
root.walkRules((rule) => {
  if (rule.parent?.type === "atrule" && rule.parent.name === "keyframes") return;
  const sels = rule.selectors.map((s) => s.trim());
  // token blocks: replaced by the mapping above
  if (sels.some((s) => s === ":root" || s === '[data-theme="light"]' || s === '[data-theme="dark"]')) { rule.remove(); return; }
  if (sels.some((s) => s === "*" || s === "*::before")) {
    if (rule.parent?.type === "root") { rule.remove(); return; }
  }
  const kept = sels.filter((s) => !DROP.test(s.replace(/^\[data-theme="(dark|light)"\]\s*/, "")));
  if (!kept.length) { rule.remove(); return; }
  rule.selectors = kept.map(scope);
});
root.walkDecls((d) => {
  if (d.prop === "animation" || d.prop === "animation-name") {
    d.value = d.value.replace(/\b(pulse|blink|spin|enter|fade|pop|slide)\b/g, "ecat-$1");
    // endless eased animations cost CPU on the robot PC without a GPU: two steps instead
    if (/infinite/.test(d.value) && !/ecat-spin/.test(d.value)) d.value = d.value.replace(/\b(ease-in-out|ease|linear)\b/, "").replace(/infinite/, "steps(2, start) infinite").replace(/\s+/g, " ").trim();
  }
});
root.walkAtRules((at) => { if (at.name === "media" && !at.nodes?.length) at.remove(); });
fs.writeFileSync(out, TOKENS + root.toString().replace(/\n{3,}/g, "\n\n"));
console.log(`wrote ${path.relative(process.cwd(), out)}`);
