//projectTemplateGenerator.js

import fs from "fs-extra";
import path from "node:path";

const EMPTY_BT_ROOT = '<?xml version="1.0" encoding="UTF-8"?>\n<root BTCPP_format="4">\n</root>\n';

// A blank project still needs structurally valid files: the IO, tree and path
// pages parse these and failed with HTTP 500 on comment-only placeholders.
// Program skeletons (no user data) are copied from the defaults; data files
// get empty but valid content.
const BLANK_SKELETONS = {
  "do_di.xml": EMPTY_BT_ROOT,
  "do_di_undo.xml": EMPTY_BT_ROOT,
  "template.xml": `<?xml version="1.0" encoding="UTF-8"?>
<root BTCPP_format="4">
  <include path="do_di.xml"/>
  <BehaviorTree ID="main_tree">
    <Sequence ID="main_tree_root" name="main_tree_sequennce(dont_delete_it)">
    </Sequence>
  </BehaviorTree>
</root>
`,
  "points.yaml": 'points_file_name: ""\npoints: []\n',
  "points_undo.yaml": 'points_file_name: ""\npoints: []\n',
};
// programs.yaml: every project starts with the starter motion program
const BLANK_COPY_DEFAULTS = new Set(["main_tree.xml", "programs.yaml"]);

function getFallbackContent(filename) {
  if (filename.endsWith(".yaml")) return "# autogenerated\n";
  if (filename.endsWith(".xml")) return "<!-- autogenerated -->\n";
  if (filename.endsWith(".json")) return "{}\n";
  if (filename.endsWith(".sh")) return "#!/bin/bash\n";
  return "";
}

/**
 * mode:
 *  - 'standard' → copy defaults if available
 *  - 'blank'    → never copy defaults, always fallback
 *
 * NOTE: template source values look like "defaults/points.yaml"
 * but baseDir already points to pm_defaults, so we strip the
 * leading "defaults/" segment before resolving the srcPath.
 */
async function generateFromTemplate(
  template,
  projectPath,
  baseDir,
  mode = "standard"
) {
  // Create directories
  for (const dir of template.directories) {
    await fs.ensureDir(path.join(projectPath, dir));
  }

  // Create files
  for (const [scope, files] of Object.entries(template.files)) {
    const targetDir =
      scope === "root"
        ? projectPath
        : path.join(projectPath, scope);

    await fs.ensureDir(targetDir);

    for (const [filename, source] of Object.entries(files)) {
      const dstPath = path.join(targetDir, filename);

      if (await fs.pathExists(dstPath)) continue;

      // Normalize "defaults/" prefix
      const normalizedSource = source.replace(/^defaults\//, "");
      const srcPath = path.join(baseDir, normalizedSource);

      const shouldCopyDefaults =
        (mode === "standard" || BLANK_COPY_DEFAULTS.has(filename)) &&
        (await fs.pathExists(srcPath));

      if (mode === "blank" && BLANK_SKELETONS[filename] !== undefined) {
        await fs.writeFile(dstPath, BLANK_SKELETONS[filename], "utf8");
      } else if (shouldCopyDefaults) {
        await fs.copy(srcPath, dstPath);
      } else {
        if (mode === "standard") {
          console.warn(
            `[generateFromTemplate] Default not found: ${srcPath} — using fallback`
          );
        }

        const fallback = getFallbackContent(filename);
        await fs.writeFile(dstPath, fallback, "utf8");
      }

      if (filename.endsWith(".sh")) {
        await fs.chmod(dstPath, 0o755);
      }
    }
  }
}

export { generateFromTemplate };